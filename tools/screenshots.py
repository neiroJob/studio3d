"""Скриншоты для README на синтетических демо-данных.

Нужны: запущенный веб (например, `python manage.py runserver 127.0.0.1:8001`), чистая база,
`python manage.py demo_data --hold 600` в соседнем терминале, Playwright для Python
(`pip install playwright && playwright install chromium`).

    python tools/screenshots.py http://127.0.0.1:8001 assets/github
"""

import sys
import tempfile
from pathlib import Path

from playwright.sync_api import sync_playwright

BASE = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8001"
OUT = Path(sys.argv[2] if len(sys.argv) > 2 else "assets/github")
USER, PASSWORD = "admin", "Demo-studio-2026"

BAD_GCODE = (
    "; generated by OrcaSlicer 2.4.1\nSTART_PRINT EXTRUDER_TEMP=240 BED_TEMP=80\nT0\n"
    + "G1 X1\n" * 200
    + "; printer_model = Generic Klipper Printer\n"
)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    with sync_playwright() as pw:
        browser = pw.chromium.launch()
        page = browser.new_page(
            viewport={"width": 1440, "height": 900}, device_scale_factor=1
        )
        page.goto(BASE + "/")
        if "/setup/" in page.url:
            page.fill("#id_first_name", "Администратор")
            page.fill("#id_username", USER)
            page.fill("#id_password1", PASSWORD)
            page.fill("#id_password2", PASSWORD)
            page.fill("#id_studio_name", "Студия 3D")
            page.fill("#id_price_kwh", "7.45")
            page.click("form.login-card button[type=submit]")
        else:
            page.goto(BASE + "/login/")
            page.fill("#id_username", USER)
            page.fill("#id_password", PASSWORD)
            page.click("form.login-card button[type=submit]")
        page.wait_for_load_state()

        page.goto(BASE + "/")
        page.wait_for_timeout(1500)
        page.screenshot(path=OUT / "dashboard.png")

        first = page.locator(".tile a").first.get_attribute("href")
        page.goto(BASE + first)
        page.wait_for_timeout(1500)
        page.screenshot(path=OUT / "printer.png")

        page.goto(BASE + first + "?tab=history")
        page.screenshot(path=OUT / "history.png")

        page.goto(BASE + "/")
        href = page.locator(".tile.err a").first.get_attribute("href")
        page.goto(BASE + href)
        page.wait_for_timeout(1000)
        page.screenshot(path=OUT / "printer-error.png")

        page.goto(BASE + href + "?tab=files")
        with tempfile.NamedTemporaryFile(
            "w", suffix=".gcode", prefix="project_2_PETG_", delete=False
        ) as f:
            f.write(BAD_GCODE)
        page.set_input_files("input[type=file]", f.name)
        page.click("form[data-upload] button[type=submit]")
        page.wait_for_selector(".upload-warn:not([hidden])")
        page.screenshot(path=OUT / "gcode-check.png")

        page.goto(BASE + "/printers/add/")
        page.select_option("#id_profile_id", "qidi_q1_pro")
        page.fill("#id_name", "Q1Pro-07")
        page.fill("#id_host", "192.168.10.27")
        page.screenshot(path=OUT / "add-printer.png", full_page=True)

        mobile = browser.new_page(
            viewport={"width": 390, "height": 844},
            device_scale_factor=2,
            color_scheme="dark",
        )
        mobile.context.add_cookies(page.context.cookies())
        mobile.goto(BASE + "/")
        mobile.wait_for_timeout(1500)
        mobile.screenshot(path=OUT / "mobile-dark.png")
        browser.close()
    print("Готово:", ", ".join(sorted(p.name for p in OUT.glob("*.png"))))


if __name__ == "__main__":
    main()
